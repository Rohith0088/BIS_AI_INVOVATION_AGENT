-- BIS Sahayak schema for Supabase PostgreSQL

CREATE TABLE IF NOT EXISTS public.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  email varchar(255) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  phone varchar(50),
  organisation varchar(255),
  role varchar(255),
  region varchar(255),
  access_type varchar(255) NOT NULL DEFAULT 'Enterprise portal',
  profile_image text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Safe migration for databases where public.users already exists.
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS phone varchar(50);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS profile_image text;

CREATE TABLE IF NOT EXISTS public.standards (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  is_code varchar(255) NOT NULL UNIQUE,
  title varchar(255) NOT NULL,
  category varchar(255),
  department varchar(255),
  summary text,
  scope text,
  is_mandatory_qco boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.chat_conversations (
  id char(36) PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  title varchar(160) NOT NULL DEFAULT 'New conversation',
  mode varchar(20) NOT NULL DEFAULT 'consumer' CHECK (mode IN ('consumer', 'industry')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_chat_conversations_user_updated
  ON public.chat_conversations (user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS public.chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id char(36) NOT NULL REFERENCES public.chat_conversations(id) ON DELETE CASCADE,
  user_id integer REFERENCES public.users(id) ON DELETE SET NULL,
  sender varchar(20) NOT NULL CHECK (sender IN ('user', 'assistant', 'system')),
  message_text text NOT NULL,
  mode varchar(20) NOT NULL DEFAULT 'consumer' CHECK (mode IN ('consumer', 'industry')),
  confidence varchar(20),
  cited_clauses jsonb,
  source_card jsonb,
  suggested_actions jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_chat_conversation ON public.chat_messages (conversation_id);
CREATE INDEX IF NOT EXISTS idx_chat_user ON public.chat_messages (user_id);
CREATE INDEX IF NOT EXISTS idx_chat_created ON public.chat_messages (created_at);

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS users_set_updated_at ON public.users;
CREATE TRIGGER users_set_updated_at
BEFORE UPDATE ON public.users
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS standards_set_updated_at ON public.standards;
CREATE TRIGGER standards_set_updated_at
BEFORE UPDATE ON public.standards
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

