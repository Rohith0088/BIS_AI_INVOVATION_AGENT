app.post("/api/auth/signup", async (req, res) => {
  try {
    if (!enforceAuthRateLimit(req, res)) return;
    const { name, email, password, organisation, role, region } = req.body ?? {};

    if (!name || !email || !password) {
      return res.status(400).json({ message: "Name, email and password are required." });
    }

    const safeEmail = String(email).trim().toLowerCase();
    const safeName = String(name).trim();
    const safeOrganisation = String(organisation ?? "").trim();
    const safeRole = String(role ?? "").trim();
    const safeRegion = String(region ?? "").trim();

    const { rows: existingRows } = await dbPool.query(
      "SELECT id FROM users WHERE email = $1 LIMIT 1",
      [safeEmail]
    );

    if (existingRows.length > 0) {
      return res.status(409).json({ message: "This account already exists. Please sign in instead." });
    }

    const passwordHash = await bcrypt.hash(String(password), 10);

     const { rows: insertedUsers } = await dbPool.query(
      `INSERT INTO users (name, email, password_hash, phone, organisation, role, region, access_type)
       VALUES ($1, $2, $3, $4, $5, $6, $7, 'Enterprise portal')
       RETURNING id`,
      [safeName, safeEmail, passwordHash, '', safeOrganisation, safeRole, safeRegion]
    );
    setSessionCookie(res, insertedUsers[0].id);

    return res.status(201).json({
      message: "User registered successfully.",
      user: {
        id: insertedUsers[0].id,
        name: safeName,
        email: safeEmail,
        organisation: safeOrganisation,
        role: safeRole,
        region: safeRegion,
      },
    });
  } catch (error: any) {
    console.error("Signup error:", error);
    if (error?.code === "23505") {
      return res.status(409).json({ message: "This email is already registered." });
    }

    return res.status(500).json({ message: "Internal server error during signup." });
  }
});

app.post("/api/auth/login", async (req, res) => {
  try {
    if (!enforceAuthRateLimit(req, res)) return;
    const { email, password } = req.body ?? {};

    if (!email || !password) {
      return res.status(400).json({ message: "Email and password are required." });
    }

    const safeEmail = String(email).trim().toLowerCase();
    const { rows } = await dbPool.query(
      "SELECT * FROM users WHERE email = $1 LIMIT 1",
      [safeEmail]
    );

    if (!rows.length) {
      return res.status(401).json({ message: "Invalid email or password." });
    }

    const user = rows[0];
    const passwordMatches = await bcrypt.compare(String(password), user.password_hash);

    if (!passwordMatches) {
      return res.status(401).json({ message: "Invalid email or password." });
    }

    setSessionCookie(res, user.id);

    return res.json({
      message: "Login successful.",
      user: {
        id: user.id,
        name: user.name,
        email: user.email,
        phone: user.phone || '',
        organisation: user.organisation,
        role: user.role,
        region: user.region,
        accessType: user.access_type,
        profileImage: user.profile_image || '',
      },
    });
  } catch (error) {
    console.error("Login error:", error);
    return res.status(500).json({ message: "Internal server error during login." });
  }
});

