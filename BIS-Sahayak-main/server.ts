function enforceAuthRateLimit(req: express.Request, res: express.Response): boolean {
  const key = req.ip || "unknown";
  const now = Date.now();
  const attempt = authAttempts.get(key);
  if (!attempt || attempt.resetAt <= now) {
    authAttempts.set(key, { count: 1, resetAt: now + 15 * 60 * 1000 });
    return true;
  }
  attempt.count += 1;
  if (attempt.count > 10) {
    res.status(429).json({ message: "Too many authentication attempts. Try again later." });
    return false;
  }
  return true;
}

function setSessionCookie(res: express.Response, userId: number) {
  const token = crypto.randomBytes(32).toString("hex");
  sessions.set(token, { userId, expiresAt: Date.now() + 1000 * 60 * 60 * 24 * 7 });
  res.setHeader("Set-Cookie", `bis_session=${token}; HttpOnly; Path=/; SameSite=Lax; Max-Age=604800${isProductionRuntime ? "; Secure" : ""}`);
}

function getSessionUserId(req: express.Request): number | null {
  const token = req.headers.cookie?.match(/(?:^|;\s*)bis_session=([^;]+)/)?.[1];
  if (!token) return null;
  const session = sessions.get(token);
  if (!session || session.expiresAt < Date.now()) {
    sessions.delete(token);
    return null;
  }
  return session.userId;
}

function requireSession(req: express.Request, res: express.Response): number | null {
  const userId = getSessionUserId(req);
  if (!userId) {
    res.status(401).json({ message: "Authentication is required." });
    return null;
  }
  return userId;
}

